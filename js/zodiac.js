/**
 * 根据出生日期解析属相与对应经络脏器
 * 生肖以农历春节（正月初一）为划分点，春节前属上一年生肖
 * @param {string} birthday - YYYY-MM-DD
 * @returns {object|null} { zodiac, earthlyBranch, organ, meridian, desc }
 */
export function parseZodiac(birthday) {
  if (!birthday) return null;
  const date = new Date(birthday);
  if (isNaN(date.getTime())) return null;

  const year = date.getFullYear();
  const month = date.getMonth() + 1;
  const day = date.getDate();
  const mmdd = `${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;

  // 判断是否在春节之前：若是，则生肖属上一年
  let zodiacYear = year;
  const sf = SPRING_FESTIVAL[year];
  if (sf && mmdd < sf) {
    zodiacYear = year - 1;
  } else if (!sf) {
    // 超出表范围的年份，回退到立春近似（02-04 前属上一年）
    if (mmdd < '02-04') zodiacYear = year - 1;
  }

  // 以 4 年（鼠年·子）为基准，ZODIAC_LIST[0] 对应子鼠
  const index = ((zodiacYear - 4) % 12 + 12) % 12;
  return ZODIAC_LIST[index];
}

